//! vision-probe: runs the local vision models of the performance capture
//! module (issue #187) on a video and measures them.
//!
//!   vision-probe info  --models DIR [--ep cpu|directml]
//!   vision-probe face  --models DIR --video FILE [--json OUT] [--overlay OUT.mp4]
//!   vision-probe mask  --models DIR --video FILE [--overlay OUT.mp4]
//!   vision-probe depth --models DIR --video FILE --variant v2|v2-ema|video
//!                      [--size 280x504] [--overlay OUT.mp4] [--mesh]
//!   vision-probe bench --models DIR --video FILE [--size 280x504] [--out OUT.json]
//!
//! Common options: --ep cpu|directml (default cpu), --threads N (default:
//! ONNX Runtime's choice), --frames N (stop after N frames).

