const OVERLAY_W: usize = 960;
const OVERLAY_H: usize = 540;

struct Args {
    command: String,
    opts: HashMap<String, String>,
    flags: Vec<String>,
}

impl Args {
    fn parse() -> Result<Self> {
        let mut it = std::env::args().skip(1);
        let command = it
            .next()
            .context("usage: vision-probe <info|face|mask|depth|bench> [options]")?;
        let (mut opts, mut flags) = (HashMap::new(), Vec::new());
        let rest: Vec<String> = it.collect();
        let mut i = 0;
        while i < rest.len() {
            let key = rest[i]
                .strip_prefix("--")
                .with_context(|| format!("unexpected {}", rest[i]))?;
            match rest.get(i + 1) {
                Some(v) if !v.starts_with("--") => {
                    opts.insert(key.to_owned(), v.clone());
                    i += 2;
                }
                _ => {
                    flags.push(key.to_owned());
                    i += 1;
                }
            }
        }
        Ok(Self {
            command,
            opts,
            flags,
        })
    }

    fn get(&self, k: &str) -> Option<&str> {
        self.opts.get(k).map(String::as_str)
    }

    fn need(&self, k: &str) -> Result<&str> {
        self.get(k).with_context(|| format!("--{k} is required"))
    }

    fn path(&self, k: &str) -> Result<PathBuf> {
        Ok(self.need(k)?.into())
    }

    fn flag(&self, k: &str) -> bool {
        self.flags.iter().any(|f| f == k)
    }

    fn ep(&self) -> Result<Ep> {
        Ep::parse(self.get("ep").unwrap_or("cpu"))
    }

    fn threads(&self) -> Result<usize> {
        Ok(self
            .get("threads")
            .map(str::parse)
            .transpose()?
            .unwrap_or(0))
    }

    fn frames(&self) -> Result<Option<usize>> {
        Ok(self.get("frames").map(str::parse).transpose()?)
    }

    fn size(&self) -> Result<(usize, usize)> {
        let s = self.get("size").unwrap_or("280x504");
        let (h, w) = s.split_once('x').context("--size is HEIGHTxWIDTH")?;
        Ok((h.parse()?, w.parse()?))
    }
}

fn main() -> Result<()> {
    let args = Args::parse()?;
    match args.command.as_str() {
        "info" => info(&args),
        "face" => {
            let r = run_face(
                &args,
                args.get("json").map(Path::new),
                args.get("overlay").map(Path::new),
            )?;
            println!("{}", serde_json::to_string_pretty(&r)?);
            Ok(())
        }
        "mask" => {
            let r = run_mask(&args, args.get("overlay").map(Path::new))?;
            println!("{}", serde_json::to_string_pretty(&r)?);
            Ok(())
        }
        "depth" => {
            let r = run_depth(
                &args,
                args.need("variant")?,
                args.get("overlay").map(Path::new),
                args.flag("mesh"),
            )?;
            println!("{}", serde_json::to_string_pretty(&r)?);
            Ok(())
        }
        "bench" => bench(&args),
        other => bail!("unknown command {other}"),
    }
}

fn info(args: &Args) -> Result<()> {
    let dir = args.path("models")?;
    let (ep, threads) = (args.ep()?, args.threads()?);
    let mut names: Vec<_> = std::fs::read_dir(&dir)?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "onnx"))
        .collect();
    names.sort();
    for path in names {
        let t = Instant::now();
        let m = runtime::load(&path, ep, threads)?;
        println!("{} (loaded in {:.0} ms)", m.describe(), ms(t));
    }
    Ok(())
}

fn open(args: &Args) -> Result<(video::Probe, Reader, PathBuf)> {
    let path = args.path("video")?;
    let p = video::probe(&path)?;
    let reader = Reader::open(&path, p.width, p.height, args.frames()?)?;
    Ok((p, reader, path))
}

#[derive(Serialize)]
struct Common {
    video: String,
    width: usize,
    height: usize,
    fps: f64,
    frames: usize,
    ep: Ep,
    fallback: Option<String>,
    decode_ms: f64,
    wall_ms: f64,
}

#[derive(Serialize)]
struct FaceReport {
    common: Common,
    frames_with_face: usize,
    frames_without_face: usize,
    frames_with_several_faces: usize,
    max_faces: usize,
    /// Median face height as a share of the frame height.
    median_face_height: f32,
    ms_per_frame: f64,
    times: face::FaceTimes,
    /// Person mask runs for the head search, not in ms_per_frame.
    head_search_mask_ms: f64,
    json_bytes: Option<u64>,
}

fn run_face(args: &Args, json_out: Option<&Path>, overlay: Option<&Path>) -> Result<FaceReport> {
    let wall = Instant::now();
    let (p, mut reader, path) = open(args)?;
    let dir = args.path("models")?;
    let mut tracker = FaceTracker::load(&dir, args.ep()?, args.threads()?)?;
    let mut seg = Segmenter::load(&dir, args.ep()?, args.threads()?)?;
    let mut writer = overlay
        .map(|o| Writer::create(o, OVERLAY_W, OVERLAY_H, p.fps))
        .transpose()?;
    let (mut with, mut without, mut several, mut max_faces, mut n) = (0, 0, 0, 0, 0);
    let (mut decode_ms, mut heights) = (0.0, Vec::new());
    let mut frames_json = Vec::new();
    loop {
        let t = Instant::now();
        let Some(frame) = reader.next_frame()? else {
            break;
        };
        decode_ms += ms(t);
        let (result, seen) = tracker.process(&frame, &mut |f| {
            Ok(seg.segment(f)?.head_region(f.width, f.height))
        })?;
        if let Some(k) = seen {
            max_faces = max_faces.max(k);
            several += usize::from(k > 1);
        }
        match &result {
            Some(r) => {
                with += 1;
                let (y0, y1) = r
                    .landmarks
                    .iter()
                    .fold((f32::MAX, f32::MIN), |(a, b), l| (a.min(l[1]), b.max(l[1])));
                heights.push(y1 - y0);
            }
            None => without += 1,
        }
        if json_out.is_some() {
            let faces: Vec<_> = result
                .iter()
                .map(|r| {
                    let blend: serde_json::Map<String, serde_json::Value> =
                        BLENDSHAPE_NAMES.iter().zip(r.blendshapes).map(|(k, v)| ((*k).to_owned(), json!(round(v)))).collect();
                    json!({
                        "landmarks": r.landmarks.iter().map(|l| [round(l[0]), round(l[1]), round(l[2])]).collect::<Vec<_>>(),
                        "blendshapes": blend,
                    })
                })
                .collect();
            frames_json
                .push(json!({ "t_ms": (n as f64 * 1000.0 / p.fps).round(), "faces": faces }));
        }
        if let Some(w) = writer.as_mut() {
            let mut out = draw::scaled(&frame, OVERLAY_W, OVERLAY_H);
            if let Some(r) = &result {
                draw::mesh(
                    &mut out,
                    &r.landmarks,
                    [40, 40, 48],
                    [150, 220, 255],
                    [255, 200, 80],
                );
            }
            w.write(&out)?;
        }
        n += 1;
    }
    if let Some(w) = writer {
        w.finish()?;
    }
    let mut json_bytes = None;
    if let Some(out) = json_out {
        let doc = json!({
            "version": 1,
            "source": { "file": path.file_name().map(|f| f.to_string_lossy()), "width": p.width, "height": p.height, "fps": p.fps, "frames": n },
            "model": { "name": "MediaPipe Face Landmarker", "version": "float16/1" },
            "frames": frames_json,
        });
        std::fs::write(out, serde_json::to_vec(&doc)?)?;
        json_bytes = Some(std::fs::metadata(out)?.len());
    }
    heights.sort_by(f32::total_cmp);
    let t = &tracker.times;
    let [det, ..] = tracker.models();
    Ok(FaceReport {
        common: Common {
            video: path.display().to_string(),
            width: p.width,
            height: p.height,
            fps: p.fps,
            frames: n,
            ep: det.ep,
            fallback: det.fallback_reason.clone(),
            decode_ms,
            wall_ms: ms(wall),
        },
        frames_with_face: with,
        frames_without_face: without,
        frames_with_several_faces: several,
        max_faces,
        median_face_height: heights.get(heights.len() / 2).copied().unwrap_or(0.0),
        ms_per_frame: (t.detector_ms + t.landmarks_ms + t.blendshapes_ms + t.preprocess_ms)
            / n.max(1) as f64,
        times: tracker.times,
        head_search_mask_ms: seg.run_ms + seg.preprocess_ms,
        json_bytes,
    })
}

fn round(v: f32) -> f64 {
    (v as f64 * 1e5).round() / 1e5
}

/// A frame much unlike the one before it is a cut in the take (the test
/// take joins two answers), not motion: its pairs are left out of the
/// frame-to-frame measures.
struct CutDetector {
    last: Option<Vec<f32>>,
}

impl CutDetector {
    fn is_cut(&mut self, frame: &Frame) -> bool {
        let thumb = draw::scaled(frame, 64, 36)
            .rgb
            .iter()
            .map(|&v| v as f32)
            .collect::<Vec<_>>();
        let cut = self.last.as_ref().is_some_and(|l| {
            l.iter()
                .zip(&thumb)
                .map(|(a, b)| (a - b).abs())
                .sum::<f32>()
                / thumb.len() as f32
                > 25.0
        });
        self.last = Some(thumb);
        cut
    }
}

#[derive(Serialize)]
struct MaskReport {
    common: Common,
    ms_per_frame: f64,
    run_ms: f64,
    preprocess_ms: f64,
    /// Person pixels' overlap between consecutive frames.
    mean_iou: f32,
    min_iou: f32,
    /// Pairs whose overlap is under 0.9: a sudden jump in the mask.
    jumps: usize,
    /// Share of the person by class, averaged over frames: hair, body skin,
    /// face skin, clothes, other.
    class_share: [f32; 5],
}

fn run_mask(args: &Args, overlay: Option<&Path>) -> Result<MaskReport> {
    let wall = Instant::now();
    let (p, mut reader, path) = open(args)?;
    let mut seg = Segmenter::load(&args.path("models")?, args.ep()?, args.threads()?)?;
    let mut writer = overlay
        .map(|o| Writer::create(o, OVERLAY_W, OVERLAY_H, p.fps))
        .transpose()?;
    let mut cuts = CutDetector { last: None };
    let (mut last, mut ious, mut jumps, mut n, mut decode_ms) =
        (None::<mask::Mask>, Vec::new(), 0, 0, 0.0);
    let mut share = [0f32; 5];
    loop {
        let t = Instant::now();
        let Some(frame) = reader.next_frame()? else {
            break;
        };
        decode_ms += ms(t);
        let cut = cuts.is_cut(&frame);
        let m = seg.segment(&frame)?;
        if let (Some(prev), false) = (&last, cut) {
            let iou = m.iou(prev);
            ious.push(iou);
            jumps += usize::from(iou < 0.9);
        }
        let mut counts = [0usize; 6];
        for i in 0..mask::SIZE * mask::SIZE {
            counts[m.class_at(i)] += 1;
        }
        let person: usize = counts[1..].iter().sum();
        for c in 0..5 {
            share[c] += counts[c + 1] as f32 / person.max(1) as f32;
        }
        if let Some(w) = writer.as_mut() {
            // Person in color by class over a dimmed frame.
            const COLORS: [[f32; 3]; 6] = [
                [0.0; 3],
                [230.0, 80.0, 200.0],
                [250.0, 170.0, 90.0],
                [255.0, 230.0, 120.0],
                [80.0, 160.0, 255.0],
                [120.0, 255.0, 140.0],
            ];
            let mut out = draw::scaled(&frame, OVERLAY_W, OVERLAY_H);
            for y in 0..OVERLAY_H {
                for x in 0..OVERLAY_W {
                    let (nx, ny) = (
                        (x as f32 + 0.5) / OVERLAY_W as f32,
                        (y as f32 + 0.5) / OVERLAY_H as f32,
                    );
                    let pp = m.person_at(nx, ny);
                    let gi = ((ny * mask::SIZE as f32) as usize).min(mask::SIZE - 1) * mask::SIZE
                        + ((nx * mask::SIZE as f32) as usize).min(mask::SIZE - 1);
                    let col = COLORS[m.class_at(gi)];
                    let i = (y * OVERLAY_W + x) * 3;
                    for c in 0..3 {
                        let base = out.rgb[i + c] as f32 * 0.35;
                        out.rgb[i + c] = if pp >= 0.5 {
                            (base * 0.4 + col[c] * 0.6) as u8
                        } else {
                            base as u8
                        };
                    }
                }
            }
            w.write(&out)?;
        }
        last = Some(m);
        n += 1;
    }
    if let Some(w) = writer {
        w.finish()?;
    }
    let mean_iou = ious.iter().sum::<f32>() / ious.len().max(1) as f32;
    Ok(MaskReport {
        common: Common {
            video: path.display().to_string(),
            width: p.width,
            height: p.height,
            fps: p.fps,
            frames: n,
            ep: seg.model.ep,
            fallback: seg.model.fallback_reason.clone(),
            decode_ms,
            wall_ms: ms(wall),
        },
        ms_per_frame: (seg.run_ms + seg.preprocess_ms) / n.max(1) as f64,
        run_ms: seg.run_ms,
        preprocess_ms: seg.preprocess_ms,
        mean_iou,
        min_iou: ious.iter().copied().fold(1.0, f32::min),
        jumps,
        class_share: share.map(|s| s / n.max(1) as f32),
    })
}

#[derive(Serialize)]
struct DepthReport {
    common: Common,
    variant: String,
    input: String,
    ms_per_frame: f64,
    times: depth::DepthTimes,
    /// Mean frame-to-frame change of the normalized depth (0..1) on the
    /// static background, where the true change is zero.
    background_flicker: f32,
    /// The same on the person, who moves: true change plus flicker.
    person_change: f32,
}

struct Pending {
    background: Vec<bool>,
    cut: bool,
    face: Option<Vec<[f32; 3]>>,
}

fn run_depth(
    args: &Args,
    variant: &str,
    overlay: Option<&Path>,
    mesh: bool,
) -> Result<DepthReport> {
    let wall = Instant::now();
    let (p, mut reader, path) = open(args)?;
    let (h, w) = args.size()?;
    let dir = args.path("models")?;
    let (ep, threads) = (args.ep()?, args.threads()?);
    enum Est {
        One(depth::PerFrame),
        Video(depth::Windowed),
    }
    let mut est = match variant {
        "v2" | "v2-ema" => Est::One(depth::PerFrame::load(
            &dir.join(format!("depth_anything_v2_small_{h}x{w}.onnx")),
            w,
            h,
            ep,
            threads,
            (variant == "v2-ema").then_some(0.5),
        )?),
        "video" => Est::Video(depth::Windowed::load(
            &dir.join(format!("video_depth_anything_small_32x{h}x{w}.onnx")),
            w,
            h,
            ep,
            threads,
        )?),
        _ => bail!("--variant is v2, v2-ema or video"),
    };
    let mut seg = Segmenter::load(&dir, Ep::Cpu, threads)?;
    let mut tracker = if mesh {
        Some(FaceTracker::load(&dir, Ep::Cpu, threads)?)
    } else {
        None
    };
    let mut writer = overlay
        .map(|o| Writer::create(o, OVERLAY_W, OVERLAY_H, p.fps))
        .transpose()?;
    let mut cuts = CutDetector { last: None };
    let mut pending: HashMap<usize, Pending> = HashMap::new();
    let (mut prev_norm, mut bg_sum, mut bg_n, mut person_sum, mut person_n) =
        (None::<Vec<f32>>, 0f64, 0usize, 0f64, 0usize);
    let (mut n, mut decode_ms) = (0, 0.0);
    let mut consume =
        |i: usize, d: depth::DepthMap, pending: &mut HashMap<usize, Pending>| -> Result<()> {
            let info = pending.remove(&i).context("depth for an unknown frame")?;
            let norm = d.normalized();
            if let (Some(prev), false) = (&prev_norm, info.cut) {
                for y in 0..d.height {
                    for x in 0..d.width {
                        let gx = x * mask::SIZE / d.width;
                        let gy = y * mask::SIZE / d.height;
                        let k = y * d.width + x;
                        let change = (norm[k] - prev[k]).abs() as f64;
                        if info.background[gy * mask::SIZE + gx] {
                            bg_sum += change;
                            bg_n += 1;
                        } else {
                            person_sum += change;
                            person_n += 1;
                        }
                    }
                }
            }
            if let Some(wr) = writer.as_mut() {
                let mut out = Frame::new(OVERLAY_W, OVERLAY_H);
                let nd = depth::DepthMap {
                    data: norm.clone(),
                    ..d
                };
                for y in 0..OVERLAY_H {
                    for x in 0..OVERLAY_W {
                        let (nx, ny) = (
                            (x as f32 + 0.5) / OVERLAY_W as f32,
                            (y as f32 + 0.5) / OVERLAY_H as f32,
                        );
                        let gi = ((ny * mask::SIZE as f32) as usize).min(mask::SIZE - 1)
                            * mask::SIZE
                            + ((nx * mask::SIZE as f32) as usize).min(mask::SIZE - 1);
                        if !info.background[gi] {
                            out.put(x as i64, y as i64, draw::depth_color(nd.at(nx, ny)));
                        }
                    }
                }
                if let Some(lm) = &info.face {
                    let pt = |i: u16| {
                        [
                            lm[i as usize][0] * OVERLAY_W as f32,
                            lm[i as usize][1] * OVERLAY_H as f32,
                        ]
                    };
                    for t in &edges::TRIANGLES {
                        draw::line(&mut out, pt(t[0]), pt(t[1]), [235, 235, 235]);
                        draw::line(&mut out, pt(t[1]), pt(t[2]), [235, 235, 235]);
                        draw::line(&mut out, pt(t[2]), pt(t[0]), [235, 235, 235]);
                    }
                }
                wr.write(&out)?;
            }
            prev_norm = Some(norm);
            Ok(())
        };
    loop {
        let t = Instant::now();
        let Some(frame) = reader.next_frame()? else {
            break;
        };
        decode_ms += ms(t);
        let cut = cuts.is_cut(&frame);
        let m = seg.segment(&frame)?;
        let background = (0..mask::SIZE * mask::SIZE)
            .map(|i| m.person(i) < 0.5)
            .collect();
        let face = match tracker.as_mut() {
            Some(tr) => {
                let head = m.head_region(frame.width, frame.height);
                tr.process(&frame, &mut |_| Ok(head))?
                    .0
                    .map(|r| r.landmarks)
            }
            None => None,
        };
        pending.insert(
            n,
            Pending {
                background,
                cut,
                face,
            },
        );
        let done = match &mut est {
            Est::One(e) => vec![(n, e.infer(&frame)?)],
            Est::Video(e) => e.push(&frame)?,
        };
        for (i, d) in done {
            consume(i, d, &mut pending)?;
        }
        n += 1;
    }
    if let Est::Video(e) = &mut est {
        for (i, d) in e.finish()? {
            consume(i, d, &mut pending)?;
        }
    }
    if let Some(wr) = writer {
        wr.finish()?;
    }
    let (times, model) = match est {
        Est::One(e) => {
            let m = (e.model().ep, e.model().fallback_reason.clone());
            (e.times, m)
        }
        Est::Video(e) => {
            let m = (e.model().ep, e.model().fallback_reason.clone());
            (e.times, m)
        }
    };
    Ok(DepthReport {
        common: Common {
            video: path.display().to_string(),
            width: p.width,
            height: p.height,
            fps: p.fps,
            frames: n,
            ep: model.0,
            fallback: model.1,
            decode_ms,
            wall_ms: ms(wall),
        },
        variant: variant.to_owned(),
        input: format!("{h}x{w}"),
        ms_per_frame: (times.preprocess_ms + times.run_ms + times.align_ms) / n.max(1) as f64,
        times,
        background_flicker: (bg_sum / bg_n.max(1) as f64) as f32,
        person_change: (person_sum / person_n.max(1) as f64) as f32,
    })
}

fn bench(args: &Args) -> Result<()> {
    let face = run_face(args, None, None)?;
    eprintln!("face: {:.1} ms/frame", face.ms_per_frame);
    let mask = run_mask(args, None)?;
    eprintln!("mask: {:.1} ms/frame", mask.ms_per_frame);
    let mut depths = Vec::new();
    for v in ["v2", "video"] {
        let d = run_depth(args, v, None, false)?;
        eprintln!("depth {v}: {:.1} ms/frame", d.ms_per_frame);
        depths.push(d);
    }
    let report = json!({ "face": face, "mask": mask, "depth": depths });
    let text = serde_json::to_string_pretty(&report)?;
    if let Some(out) = args.get("out") {
        std::fs::write(out, &text)?;
    }
    println!("{text}");
    Ok(())
}
