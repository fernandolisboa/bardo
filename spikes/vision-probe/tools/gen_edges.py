"""Write src/edges.rs from MediaPipe's face landmark connections (Apache-2.0).

The tessellation lists the 852 triangles of the 468-point mesh, three edges
each, in order; the contours and irises are plain edges.
"""

import pathlib
import sys

from mediapipe.tasks.python.vision.face_landmarker import FaceLandmarksConnections as C


def edges(name):
    return [(c.start, c.end) for c in getattr(C, name)]


def main(out):
    tess = edges("FACE_LANDMARKS_TESSELATION")
    triangles = []
    for i in range(0, len(tess), 3):
        (a, b), (b2, c), (c2, a2) = tess[i : i + 3]
        assert b == b2 and c == c2 and a == a2, f"edges {i}..{i + 2} are not a triangle"
        triangles.append((a, b, c))
    lines = [
        "// Generated by tools/gen_edges.py from MediaPipe's FaceLandmarksConnections",
        "// (mediapipe/tasks/python/vision/face_landmarker.py, Apache-2.0). Do not edit.",
        "",
        f"pub const TRIANGLES: [[u16; 3]; {len(triangles)}] = [",
        *[f"    [{a}, {b}, {c}]," for a, b, c in triangles],
        "];",
    ]
    for rust, name in [
        ("CONTOURS", "FACE_LANDMARKS_CONTOURS"),
        ("LEFT_IRIS", "FACE_LANDMARKS_LEFT_IRIS"),
        ("RIGHT_IRIS", "FACE_LANDMARKS_RIGHT_IRIS"),
    ]:
        e = edges(name)
        lines += ["", f"pub const {rust}: [[u16; 2]; {len(e)}] = [", *[f"    [{a}, {b}]," for a, b in e], "];"]
    pathlib.Path(out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
